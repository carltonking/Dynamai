import Foundation

/// The Hermes page's words: what the settings say, and what a conversation
/// that is starting, stopped or refused says for itself. Fields are `var` so
/// the Instinct page, the same page on another conversation, can put its own
/// name where Hermes's stands (`NotchInstinctChatStrings.chat`).
struct NotchHermesChatStrings {
    var title: String
    var description: String
    var enable: String
    var cliPath: String
    var cliPathPlaceholder: String
    var cliPathHint: String
    var requiresDynamicIsland: String
    var enableDynamicIsland: String
    var connecting: String
    var ready: String
    var placeholder: String
    var send: String
    var stop: String
    var clear: String
    var retry: String
    var emptyTitle: String
    var emptySubtitle: String
    var thinking: String
    var stopped: String
    var stoppedAtLimit: String
    var stoppedAtStepLimit: String
    var refusedByAgent: String
    var refusedCommand: String
    var refusedCommandFormat: String
    var notFoundFormat: String
    var unreachableFormat: String
    var you: String
    var copyMessage: String
    var editMessage: String
    var approvalTitle: String
    var allowOnce: String
    var allowSession: String
    var allowAlways: String
    var deny: String
    var approvalAllowed: String
    var approvalDenied: String
    var approvalExpired: String
    var reachedOut: String
    var reachedOutFormat: String
    var dictate: String
    var stopDictation: String
    var listening: String
    var dictationDenied: String
    var dictationUnavailable: String
    var speakReplies: String
    /// The number Hermes texts from (a Photon line). With it the page is the
    /// iMessage thread with Hermes instead of a conversation on this Mac.
    var number: String
    var numberPlaceholder: String
    var numberHint: String
    var recentChats: String
    var messagesToolMissingFormat: String
    /// Why Hermes would not move the session to another model.
    var modelSwitchFailedFormat: String

    func notFound(_ command: String) -> String { String(format: notFoundFormat, command) }

    func unreachable(_ reason: String) -> String { String(format: unreachableFormat, reason) }

    func modelSwitchFailed(_ reason: String) -> String { String(format: modelSwitchFailedFormat, reason) }

    func refusedCommandLine(_ subject: String) -> String {
        String(format: refusedCommandFormat, subject)
    }

    /// The line over a message Hermes sent unasked, naming the routine that
    /// wrote it when the hub said which.
    func reachedOut(_ routine: String?) -> String {
        guard let routine, !routine.isEmpty else { return reachedOut }
        return String(format: reachedOutFormat, routine)
    }
}

extension FeatureStrings {
    static func notchHermesChat(_ language: AppLanguage) -> NotchHermesChatStrings {
        switch language {
        case .enUS: return .enUS
        case .ptBR: return .ptBR
        case .es: return .es
        case .sk: return .sk
        case .de: return .de
        case .fr: return .fr
        case .it: return .it
        case .ru: return .ru
        case .tr: return .tr
        case .ja: return .ja
        case .ko: return .ko
        case .uk: return .uk
        case .zhHans: return .zhHans
        case .zhTW: return .zhTW
        case .zhHK: return .zhHK
        }
    }
}

